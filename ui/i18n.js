const HAB_LOCALES = Object.keys(HAB_MESSAGES);

/** Primary subtag of a BCP 47 tag; no/nn → nb; anything Haven does not offer → en. */
function habPickLocale(tag) {
  const primary = String(tag || "").toLowerCase().split(/[-_]/)[0];
  const mapped = primary === "no" || primary === "nn" ? "nb" : primary;
  return HAB_LOCALES.includes(mapped) ? mapped : "en";
}

const LOCALE = habPickLocale(typeof navigator !== "undefined" ? navigator.language : "en");

function fill(text, vars) {
  return text.replace(/\{(\w+)\}/g, (all, name) => (vars && name in vars ? String(vars[name]) : all));
}

/** Text by key with {placeholders} filled from `vars`. */
function t(key, vars) {
  const value = HAB_MESSAGES[LOCALE][key] ?? HAB_MESSAGES.en[key] ?? key;
  return fill(typeof value === "string" ? value : value.other, vars);
}

/** Counted text: picks the plural form for `count` and fills {count} formatted. */
function tc(key, count, vars) {
  const forms = HAB_MESSAGES[LOCALE][key] ?? HAB_MESSAGES.en[key];
  const text = forms[new Intl.PluralRules(LOCALE).select(count)] ?? forms.other;
  return fill(text, { ...vars, count: num(count) });
}

/** Text whose placeholders are DOM nodes (e.g. <code>), as a list for append(). */
function tNodes(key, nodes) {
  const parts = t(key).split(/(\{\w+\})/);
  return parts.filter(Boolean).map((part) => {
    const match = /^\{(\w+)\}$/.exec(part);
    return match && nodes[match[1]] ? nodes[match[1]] : part;
  });
}

function num(value, options) {
  return new Intl.NumberFormat(LOCALE, options).format(value);
}

/** Fills data-i18n, data-i18n-placeholder and data-i18n-aria-label below `root`. */
function localize(root) {
  document.documentElement.lang = LOCALE;
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll("[data-i18n-aria-label]")) node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
}
